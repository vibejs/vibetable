import {
  columnFilteringFeature,
  columnFacetingFeature,
  columnVisibilityFeature,
  columnSizingFeature,
  columnResizingFeature,
  columnOrderingFeature,
  columnPinningFeature,
  columnGroupingFeature,
  rowAggregationFeature,
  rowExpandingFeature,
  globalFilteringFeature,
  rowPaginationFeature,
  rowSelectionFeature,
  rowSortingFeature,
  createFilteredRowModel,
  createSortedRowModel,
  createPaginatedRowModel,
  createGroupedRowModel,
  createExpandedRowModel,
  createFacetedRowModel,
  createFacetedUniqueValues,
  filterFn_includesString,
  filterFn_inNumberRange,
  sortFn_text,
  sortFn_basic,
  aggregationFn_sum,
  tableFeatures,
  createColumnHelper,
} from '@usevibejs/table';
import type { RecordItem } from './records.ts';
export const features = tableFeatures({
  columnFilteringFeature,
  columnFacetingFeature,
  globalFilteringFeature,
  columnVisibilityFeature,
  columnSizingFeature,
  columnResizingFeature,
  columnOrderingFeature,
  columnPinningFeature,
  columnGroupingFeature,
  rowAggregationFeature,
  rowExpandingFeature,
  rowPaginationFeature,
  rowSelectionFeature,
  rowSortingFeature,
  filteredRowModel: createFilteredRowModel(),
  sortedRowModel: createSortedRowModel(),
  paginatedRowModel: createPaginatedRowModel(),
  groupedRowModel: createGroupedRowModel(),
  expandedRowModel: createExpandedRowModel(),
  facetedRowModel: createFacetedRowModel(),
  facetedUniqueValues: createFacetedUniqueValues(),
  filterFns: { includesString: filterFn_includesString, inNumberRange: filterFn_inNumberRange },
  sortFns: { text: sortFn_text, basic: sortFn_basic },
  aggregationFns: { sum: aggregationFn_sum },
});
export type Features = typeof features;
export const helper = createColumnHelper<Features, RecordItem>();
export const columns = helper.columns([
  helper.accessor('id', { header: 'Invoice', size: 130 }),
  helper.accessor('name', {
    header: 'Customer',
    size: 220,
    sortFn: 'text',
    filterFn: 'includesString',
  }),
  helper.accessor('category', { header: 'Category', size: 150, filterFn: 'includesString' }),
  helper.accessor('amount', {
    header: 'Amount',
    size: 130,
    sortFn: 'basic',
    filterFn: 'inNumberRange',
    aggregationFn: 'sum',
    cell: (context) =>
      new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' }).format(
        context.getValue(),
      ),
  }),
]);
